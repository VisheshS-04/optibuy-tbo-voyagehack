"""Monte Carlo backtest: play N sampled seasons and write the KRA scorecard.

    python scripts/run_backtest.py --sims 20

Writes reports/kpi_summary.csv, reports/kpi_runs.csv and reports/kpi_summary.md.
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from optibuy.config import PolicyConfig  # noqa: E402
from optibuy.forecast import backtest_forecaster  # noqa: E402
from optibuy.planner import Engine, simulate  # noqa: E402

CR = 1e7


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sims", type=int, default=20)
    ap.add_argument("--budget-cr", type=float, default=20.0)
    ap.add_argument("--seed", type=int, default=2026)
    args = ap.parse_args()

    t0 = time.time()
    eng = Engine.build(seed=7, cfg=PolicyConfig(budget=args.budget_cr * CR))
    fc = backtest_forecaster(eng.world.history)
    runs, summ = simulate(eng, n_sims=args.sims, seed=args.seed)
    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    runs.to_csv(out / "kpi_runs.csv", index=False)
    summ.to_csv(out / "kpi_summary.csv")
    acc = runs.groupby("sim")[["wape_t90", "wape_t35", "wape_t10"]].first().mean()

    names = {"spot_only": "Spot only (no pre-buy)", "rule_of_thumb": "Rule of thumb (80% of last year, hard blocks)",
             "optibuy_seed_only": "OptiBuy, seed stage only", "optibuy": "OptiBuy, full rolling plan"}
    lines = [
        f"# KRA scorecard ({args.sims} simulated seasons, budget ₹{args.budget_cr:.0f} crore)", "",
        "Synthetic data. Each season is a fresh draw of true demand, disruptions and spot availability;",
        "every policy faces the same season. Profit = all margin earned on pre-bought and on-request sales,",
        "net of purchase cost, release refunds and salvage.", "",
        "| Policy | Profit (₹ cr) | Worst-5% profit (₹ cr) | ROI on capital | Sell-through | Demand served | Sold-out cohorts | Spoilage (₹ cr) | Price realisation |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for pol, r in summ.iterrows():
        roi = "n/a" if r["roi"] != r["roi"] else f"{r['roi']:.1%}"
        st = "n/a" if r["sell_through"] != r["sell_through"] else f"{r['sell_through']:.1%}"
        lines.append(f"| {names.get(pol, pol)} | {r['profit'] / CR:.2f} | {r['profit_p5'] / CR:.2f} | {roi} | {st} | "
                     f"{r['fill_rate']:.1%} | {r['soldout_share']:.1%} | {r['spoilage_value'] / CR:.2f} | {r['price_realisation']:.1%} |")
    lines += [
        "", "## Forecast accuracy (WAPE, lower is better)", "",
        f"* 26-week holdout on history: model **{fc['wape_model']:.1%}** vs seasonal naive {fc['wape_seasonal_naive']:.1%}; "
        f"P10 to P90 coverage {fc['p10_p90_coverage']:.0%} (scenario spread is widened 1.2x to compensate)",
        f"* During the simulated seasons: T-90 seed **{acc['wape_t90']:.1%}**, T-35 after booking pace "
        f"**{acc['wape_t35']:.1%}**, T-10 **{acc['wape_t10']:.1%}**", "",
        f"_Generated by scripts/run_backtest.py in {time.time() - t0:.0f} s._",
    ]
    (out / "kpi_summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
